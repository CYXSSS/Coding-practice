def hanoi(n, 起始柱, 辅助柱, 终点柱):
    """
    递归解决汉诺塔问题
    :param n: 圆盘数量
    :param 起始柱: 初始存放圆盘的柱子
    :param 辅助柱: 用于中转的柱子
    :param 终点柱: 最终目标柱子
    """
    if n == 1:
        # 基础情况：1个圆盘直接从起始柱移到终点柱
        print(f"移动圆盘 {n} 从 {起始柱} 到 {终点柱}")
    else:
        # 步骤1：将n-1个圆盘从起始柱移到辅助柱（用终点柱做临时辅助）
        hanoi(n-1, 起始柱, 终点柱, 辅助柱)
        # 步骤2：将第n个圆盘从起始柱移到终点柱
        print(f"移动圆盘 {n} 从 {起始柱} 到 {终点柱}")
        # 步骤3：将n-1个圆盘从辅助柱移到终点柱（用起始柱做临时辅助）
        hanoi(n-1, 辅助柱, 起始柱, 终点柱)

# 测试：3个圆盘，起始柱为"左"，辅助柱为"中"，终点柱为"右"
# 检验移动步骤总数是否为2^n - 1
hanoi(3, "左", "中", "右")
